def _load_patients() -> list[dict]:
    """SYNTHETIC patients from patients.json (generated by scripts/generate_patients.py)."""
    import json
    from pathlib import Path

    f = Path(__file__).with_name("patients.json")
    if f.exists():
        return json.loads(f.read_text(encoding="utf-8"))["patients"]
    return _FALLBACK_PATIENTS


PATIENTS = _load_patients()

TIMES = [f"{h:02d}:{m:02d}" for h in range(9, 17) for m in (0, 30)]
booked_slots: set[str] = set()
appointments: dict[str, dict] = {}
_seq = itertools.count(5001)


def now() -> datetime:
    return datetime.now(TZ).replace(tzinfo=None)


def slot_id(dept: str, d: str, t: str) -> str:
    return f"{dept}|{d}|{t}"


def pre_booked(dept: str, d: str, t: str) -> bool:
    return int(hashlib.md5(slot_id(dept, d, t).encode()).hexdigest(), 16) % 4 == 0


def open_slots(dept: str, d: date) -> list[dict]:
    if d.weekday() == 6:  # Sunday closed
        return []
    out = []
    cutoff = now() + timedelta(hours=1)
    for t in TIMES:
        if datetime.combine(d, datetime.strptime(t, "%H:%M").time()) < cutoff:
            continue
        sid = slot_id(dept, d.isoformat(), t)
        if sid in booked_slots or pre_booked(dept, d.isoformat(), t):
            continue
        out.append({"id": sid, "date": d.isoformat(), "time": t, "department_id": dept})
    return out


def _book(patient_id: str, sid: str) -> dict:
    dept, d, t = sid.split("|")
    aid = f"A-{next(_seq)}"
    appt = {"id": aid, "patient_id": patient_id, "department_id": dept, "department": DEPT[dept]["name"],
            "date": d, "time": t, "status": "booked", "slot_id": sid}
    appointments[aid] = appt
    booked_slots.add(sid)
    return appt


def _seed() -> None:
    d = now().date()
    for pid, dept, days, t in (("P-1001", "cardio", 5, "10:00"), ("P-1002", "gm", 3, "11:30")):
        day = d + timedelta(days=days)
        while day.weekday() == 6:
            day += timedelta(days=1)
        sid = slot_id(dept, day.isoformat(), t)
        _book(pid, sid)
    # a deterministic spread of upcoming appointments for other synthetic patients
    import random

    rnd = random.Random(7)
    depts = list(DEPT)
    for p in PATIENTS[10:30]:
        day = d + timedelta(days=rnd.randint(2, 20))
        while day.weekday() == 6:
            day += timedelta(days=1)
        dept, t = rnd.choice(depts), rnd.choice(TIMES)
        sid = slot_id(dept, day.isoformat(), t)
        if sid not in booked_slots and not pre_booked(dept, day.isoformat(), t):
            _book(p["id"], sid)


_seed()


@app.get("/health")
def health():
    return {"ok": True}


@app.get("/fhir/Department")
def departments():
    return DEPARTMENTS


@app.get("/fhir/Patient")
def patients(birthdate: str):
    return [p for p in PATIENTS if p["birthDate"] == birthdate]


@app.get("/fhir/Slot")
def slots(department: str, date: str):
    if department not in DEPT:
        raise HTTPException(404, "unknown department")
    return open_slots(department, datetime.strptime(date, "%Y-%m-%d").date())


@app.get("/fhir/Slot/next")
def next_slot(department: str, after: str):
    if department not in DEPT:
        raise HTTPException(404, "unknown department")
    d = datetime.strptime(after, "%Y-%m-%d").date()
    for i in range(1, 61):
        cand = d + timedelta(days=i)
        if open_slots(department, cand):
            return {"date": cand.isoformat()}
    return {"date": None}


@app.get("/fhir/Appointment")
def list_appointments(patient: str):
    return sorted((a for a in appointments.values() if a["patient_id"] == patient), key=lambda a: (a["date"], a["time"]))


class BookIn(BaseModel):
    patient: str
    slot: str


@app.post("/fhir/Appointment")
def book(body: BookIn):
    if body.patient not in {p["id"] for p in PATIENTS}:
        raise HTTPException(404, "unknown patient")
    dept, d, t = body.slot.split("|")
    if body.slot in booked_slots or pre_booked(dept, d, t):
        raise HTTPException(409, "slot taken")
    return _book(body.patient, body.slot)


@app.post("/fhir/Appointment/{aid}/cancel")
def cancel(aid: str):
    a = appointments.get(aid)
    if not a:
        raise HTTPException(404)
    a["status"] = "cancelled"
    booked_slots.discard(a["slot_id"])
    return a
